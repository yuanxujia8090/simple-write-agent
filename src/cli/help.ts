/** 命令行帮助文本。中文为主，保留命令与参数原名。 */
export function helpText(): string {
  return [
    "写作 Agent（writing-agent）—— 本地运行的公众号长文写作助手",
    "",
    "用法：",
    "  writing-agent [选项]",
    "",
    "不带 --file / --topic 时只做启动检查（配置与工作目录），不开始创作。",
    "带上素材或话题后进入创作主路径：读素材 → 编排 → 非交互自动批准门禁 → 导出主稿 Markdown（及 HTML）。",
    "",
    "选项：",
    "  --topic <主题>        以话题开始新会话；仅有 --file 时用文件名作话题",
    "  --file <路径>         附带 .txt / .md 素材，可重复指定",
    "  --theme <路径>        指定主题 JSON",
    "  --style <id|路径>     指定本地风格包（id 对应 ~/.writing-agent/styles/<id>；也可用目录路径）",
    "  --cwd <路径>          指定工作目录；默认从当前目录向上查找 .writing-agent 标记",
    "  --output-dir <路径>   指定导出目录（绝对路径直接用，否则相对工作目录；本版导出仍默认 articles/）",
    "  --fast                快速模式：只保留论点和终稿两个确认点（非交互下均自动批准）",
    "  --debug               输出调试日志",
    "  -h, --help            显示本帮助",
    "  -v, --version         显示版本",
    "",
    "示例：",
    "  # 素材→成稿（无 API Key 时用固定模型结果，不联网）",
    "  writing-agent --file ./notes.md --topic \"测\" --fast",
    '  writing-agent --topic "跨端状态同步为什么总翻车"',
    "  writing-agent --file ./notes.md --style demo --fast",
    "  writing-agent --cwd ~/writing/my-article",
    "",
    "说明：未配置 WRITING_AGENT_MODEL_API_KEY 时走固定结果，便于本地验收素材→主稿；配置密钥后走真实模型。",
  ].join("\n");
}
